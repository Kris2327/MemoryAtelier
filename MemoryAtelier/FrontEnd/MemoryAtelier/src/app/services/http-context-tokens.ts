import { HttpContextToken } from '@angular/common/http';

/**
 * Маркира заявка да НЕ се вгражда в SSR transfer-state-а (ng-state JSON-а, сериализиран
 * в първоначалния HTML). Ползва се за обемисти отговори (напр. пълния каталог продукти),
 * защото embed-натите в HTML-а данни увеличават директно размера на страницата, който
 * трябва да се свали преди hydration — на бавна мобилна връзка това реално бави LCP.
 * Заявката пак се прави на сървъра (SSR съдържанието остава same), просто не се копира в HTML-а —
 * клиентът я прави наново (успоредно, извън критичния път) вместо да чете кеширан резултат.
 */
export const SKIP_TRANSFER_CACHE = new HttpContextToken<boolean>(() => false);
